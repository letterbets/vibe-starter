/**
 * Generate synthetic realistic OHLC candlesticks based on a baseline price,
 * volatility, and a general trend.
 */
export function generateCandles(basePrice: number, points = 45, volatility = 0.015, trend = 0.001): CandlePoint[] {
  const candles: CandlePoint[] = [];
  let currentPrice = basePrice * (1 - points * trend * 0.5);
  const now = new Date();

  for (let i = points; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const timeStr = d.toISOString().split('T')[0];
    const dailyChange = (Math.random() - 0.48) * volatility * currentPrice + (currentPrice * trend);
    const open = currentPrice;
    const close = Math.max(0.01, open + dailyChange);
    const high = Math.max(open, close) + Math.random() * volatility * currentPrice * 0.7;
    const low = Math.min(open, close) - Math.random() * volatility * currentPrice * 0.7;
    const volume = Math.floor((Math.random() * 0.8 + 0.6) * 15000000);

    candles.push({
      time: timeStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }

  // Set the last candle to match the basePrice
  if (candles.length > 0) {
    candles[candles.length - 1].close = basePrice;
  }

  return candles;
}

